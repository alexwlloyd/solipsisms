import React, { useState, useEffect, useMemo } from 'react';
import { motion, AnimatePresence } from 'motion/react';
import { 
  Lock, 
  Unlock, 
  Brain, 
  Eye, 
  Atom, 
  Fingerprint, 
  Lightbulb, 
  ArrowRight,
  Compass,
  AlertCircle,
  Shapes,
  Sparkles
} from 'lucide-react';
import ReactMarkdown from 'react-markdown';
import { clsx, type ClassValue } from 'clsx';
import { twMerge } from 'tailwind-merge';

// --- Utilities ---
function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

// --- Data & Types ---

type AppState = 'intro' | 'trapped' | 'escape-room' | 'degrees' | 'reach-out' | 'final';

interface Scenario {
  id: string;
  title: string;
  prompt: string;
  challengeText: string;
  options: {
    id: string;
    text: string;
    description: string;
    isTrap: boolean;
  }[];
}

